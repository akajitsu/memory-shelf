import type { CSSProperties, ReactNode } from "react";
import { ZODIAC } from "@/lib/astro-glyphs.mjs";
import { seeded } from "@/lib/random";
import shelf from "./bookshelf.module.css";
import styles from "./tree.module.css";

/** A tall tile of zodiac runes carved into the bark (repeats down each side of the trunk). */
function runeTile(offset: number) {
  const glyphs = [0, 1, 2, 3].map((i) => {
    const g = ZODIAC[(offset + i * 3) % 12];
    const y = 120 + i * 260;
    return `<path transform='translate(11 ${y}) scale(.75)' d='${g.d}'/><circle cx='20' cy='${y + 9}' r='13' fill='none' stroke-width='.6' opacity='.5'/>`;
  });
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='40' height='1040' viewBox='0 0 40 1040'><g fill='none' stroke='%2383d9d4' stroke-width='1.6' stroke-linecap='round' stroke-linejoin='round'>${glyphs.join("")}</g></svg>`;
  return `url("data:image/svg+xml,${svg.replace(/#/g, "%23").replace(/"/g, "'").replace(/</g, "%3C").replace(/>/g, "%3E")}")`;
}
const RUNES_LEFT = runeTile(0);
const RUNES_RIGHT = runeTile(6);

const SPORES = (() => {
  const r = seeded(91);
  return Array.from({ length: 14 }, () => ({
    "--x": `${(r() * 100).toFixed(1)}%`,
    "--s": `${(3 + r() * 4).toFixed(1)}px`,
    "--d": `${(9 + r() * 10).toFixed(1)}s`,
    "--delay": `${(-r() * 16).toFixed(1)}s`,
    "--sway": `${((r() - 0.5) * 60).toFixed(0)}px`,
    "--c": r() < 0.6 ? "#83d9d4" : "#a89acb",
  })) as CSSProperties[];
})();

/**
 * The Great Tree: a canopy of glowing leaves (books and crystals hanging from its
 * boughs), a trunk carved with zodiac runes whose hollows hold the album books, and
 * roots plunging into mossy ground with runestones, crystals and a zodiac ring.
 * Children are book slots; rows wrap like shelves.
 */
export function TreeCase({
  children,
  label,
  dimmed = false,
  perch,
}: {
  children?: ReactNode;
  label: string;
  dimmed?: boolean;
  perch?: ReactNode;
}) {
  return (
    <section className={styles.tree} aria-label={label}>
      <div className={styles.crown} aria-hidden>
        <div className={styles.sway}>
          {/* Static artwork generated by scripts/generate-sky.mjs */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src="/sky/tree-crown.svg" alt="" decoding="async" />
        </div>
        {perch && <div className={styles.perch}>{perch}</div>}
      </div>
      <div className={styles.trunk}>
        <div className={styles.bark}>
          <span className={styles.runes} style={{ backgroundImage: RUNES_LEFT }} aria-hidden />
        </div>
        <div className={`${shelf.trunkRows} ${dimmed ? shelf.dimmed : ""}`} role="list">
          {children}
        </div>
        <div className={styles.bark}>
          <span className={styles.runes} style={{ backgroundImage: RUNES_RIGHT, animationDelay: "-3s" }} aria-hidden />
        </div>
        <span className={`${styles.wisp} ${styles.wispA}`} aria-hidden />
        <span className={`${styles.wisp} ${styles.wispB}`} aria-hidden />
        <span className={`${styles.wisp} ${styles.wispC}`} aria-hidden />
      </div>
      <div className={styles.roots} aria-hidden>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src="/sky/tree-roots.svg" alt="" decoding="async" />
      </div>
      {/* The ground the tree is planted in: it runs to the bottom of the page. */}
      <div className={styles.ground} aria-hidden>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src="/sky/tree-ground.svg" alt="" decoding="async" className={styles.groundArt} />
        <span className={`${styles.mist} ${styles.mistA}`} />
        <span className={`${styles.mist} ${styles.mistB}`} />
        {SPORES.map((v, i) => (
          <span key={i} className={styles.spore} style={v} />
        ))}
      </div>
    </section>
  );
}
